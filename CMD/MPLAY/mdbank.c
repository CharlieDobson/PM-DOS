/*
 * MDBANK.C - the instrument bank: the 128 General MIDI programs and
 * the drums of keys 35 to 81, as two-operator FM patches (MIDI.H).
 *
 * THESE PATCHES WERE MADE FOR MPLAY, from the principles of FM, and
 * owe nothing to any other bank.  Each is a modulator and a carrier in
 * the OPL's own register form, so the same table drives the chip and
 * the software synthesizer, and sounds much the same on both.
 *
 * WHAT THE NUMBERS DO.  The carrier is what is heard; its total level
 * is the loudness and its envelope the shape of the note.  The
 * modulator moves the carrier's phase: its level is the brightness
 * (0.75 dB a step; 0 is a wild 25 radians, 30 a warm 2, 48 nearly a
 * plain sine), its multiple puts the partials where they are (2 against
 * a carrier of 1 gives the odd harmonics of a clarinet, 7 the sparse
 * high ones of a bell), and its envelope makes the brightness change
 * through the note - fast for a plucked or struck sound, slow for a
 * swell.  Feedback makes the modulator itself richer, towards a
 * sawtooth by 5 or 6 and noise at 7, which is where the cymbals and
 * the snares come from.  With the connection set the two are simply
 * added, as two drawbars of an organ.
 *
 * ENVELOPES BY FAMILY.  A piano, a guitar, a mallet: sustaining with a
 * sustain level of 15, so the note dies away at the decay rate while
 * held and is damped at the release rate when let go.  An organ, a
 * wind, a string: sustaining at a level, with a slower attack for the
 * bowed and blown ones.  A drum, a bell, a gong: not sustaining, with
 * the release the same as the decay, so it dies the same way whether
 * the key is let go early or late - most files let a drum go at once.
 *
 * THE RATES SPEED UP WITH PITCH where the key scale rate bit is set
 * (strings that are short and high die sooner), and the key scale level
 * turns the high notes down where a real instrument is darker there.
 *
 * DRUMS ARE ORDINARY VOICES AT A FIXED NOTE (MDPATCH.note): a pitched
 * tone for the toms, the kicks and the bells, feedback noise with a
 * high multiple for the cymbals, the hats and the shakers.
 *
 * The OP() macro takes: flags (EG sustaining, KS key scale rate, VB
 * vibrato, TR tremolo), multiple, key scale level (1: 3 dB, 2: 1.5 dB,
 * 3: 6 dB an octave), total level, attack, decay, sustain level,
 * release, waveform (0 sine, 1 half, 2 rectified, 3 quarter pulses).
 * PATCH() takes the modulator, the carrier, the feedback (0..7), the
 * connection (0 FM, 1 added) and the note offset or fixed note.
 */
