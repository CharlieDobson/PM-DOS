#define OP( fl, mu, ks, tl, ar, dr, sl, rr, ws ) \
    { (u8)((fl) | (mu)), (u8)(((ks) << 6) | (tl)), (u8)(((ar) << 4) | (dr)), \
      (u8)(((sl) << 4) | (rr)), (u8)(ws) }
#define PATCH( mod, car, fb, cn, nt )   { { mod, car }, (u8)(((fb) << 1) | (cn)), (s8)(nt) }

