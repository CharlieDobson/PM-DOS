#!/usr/bin/perl
# mkcap.pl OUT.BAT IN.BAT [IN.BAT ...]
#
#   perl TOOLS\MKCAP.PL DISK\FDLCAP.BAT DISK\FDRTEST.BAT DISK\FDLTEST.BAT
#
# WHY THIS EXISTS.  FATGET.PL made it possible to read a test's output
# off the disk image instead of off a photograph of the screen - but
# only if the test can be made to write to a file in the first place,
# and this shell will not do that the obvious way.
#
# THIS COMMAND.COM DOES NOT CARRY A REDIRECTION INTO A BATCH FILE.
# "FDLTEST > C:\OUT.TXT" and "CALL FDLTEST > C:\OUT.TXT" both create
# the file, leave it empty, and print the whole run to the screen -
# which is a thing worth knowing about the shell and was found the
# expensive way, by watching a four-minute test finish twice with
# nothing to read afterwards.  Real MS-DOS keeps the redirection for
# the life of the batch; this one puts the handles back after the
# first command.
#
# So a capture run redirects EVERY LINE, one command at a time, and
# that is what this writes: the same batch with ">> C:\FDLOUT.TXT" on
# the end of each line, its comments dropped, and any line that
# already redirects left exactly alone.
#
# THE TEST BATCHES THEMSELVES STAY AS THEY ARE, which is the point of
# generating this rather than writing it.  They are meant to be READ -
# the reasoning is in their comments and the comments are most of the
# file - and a version with a redirection stapled to every line would
# be neither readable nor the thing that was read.
#
# The output is not kept in the tree.  Generate it, add it to MKHD's
# file list for the run, capture, and throw it away.
use strict; use warnings;

my $out = shift or die "usage: mkcap.pl OUT.BAT IN.BAT [IN.BAT ...]\n";
@ARGV or die "usage: mkcap.pl OUT.BAT IN.BAT [IN.BAT ...]\n";

my $log = 'C:' . chr(92) . 'FDLOUT.TXT';

open(my $O, '>', $out) or die "$out: $!";
binmode $O;
print $O "\@ECHO OFF\r\n";
print $O "REM GENERATED by TOOLS\\MKCAP.PL from:\r\n";
print $O "REM   $_\r\n" for @ARGV;
print $O "REM Do not edit - edit those and generate this again.\r\n";
print $O "ECHO capture > $log\r\n";

for my $src (@ARGV) {
    open(my $I, '<', $src) or die "$src: $!";
    while (my $l = <$I>) {
        $l =~ s/[\r\n]+$//;
        next if $l =~ /^\s*$/;
        next if $l =~ /^\@?ECHO OFF/i;
        next if $l =~ /^REM\b/i;
        # A line that already redirects is building its own fixture,
        # and stapling a second redirection to it would send the
        # fixture into the log instead of into the file it is for.
        if ($l =~ />/) { print $O "$l\r\n"; next; }
        print $O "$l >> $log\r\n";
    }
    close $I;
}
print $O "ECHO CAPTURE COMPLETE\r\n";
close $O;
print "$out written; add it to MKHD.CMD's file list, then read it back with\n";
print "  perl TOOLS\\FATGET.PL IMAGES\\HD16.IMG FDLOUT.TXT\n";
